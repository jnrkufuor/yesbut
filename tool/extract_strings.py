#!/usr/bin/env python3
"""Collects the app's UI copy (string literals in lib/screens and lib/widgets)
into lib/i18n/app_strings.g.dart, so a new language can be translated in one
go before the app shows it (no English flash on the next screen).
Run after changing UI text:  python3 tool/extract_strings.py"""
import re, pathlib, json
root = pathlib.Path(__file__).resolve().parent.parent
lit = re.compile(r"""(?<![A-Za-z0-9_$])(?:'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)")""")
skip_line = re.compile(r"^\s*(import|export|part)\b|fontFamily|RegExp\(|Uri\.|https?://|ValueKey|tooltip: null")
out = set()
for folder in ['lib/screens', 'lib/widgets']:
    for f in sorted((root / folder).rglob('*.dart')):
        for line in f.read_text().splitlines():
            if skip_line.search(line) or line.strip().startswith('//'):
                continue
            for m in lit.finditer(line):
                s = m.group(1) if m.group(1) is not None else m.group(2)
                if not s or '$' in s or '\\' in s or len(s) < 2 or len(s) > 300:
                    continue
                if not re.search(r'[A-Za-z]{2}', s):
                    continue
                if re.fullmatch(r'[a-z0-9_.\-/:]+', s):   # keys, ids, paths
                    continue
                if re.search(r'[{}<>=]|\.dart|\.json|\.png|package:|_[a-z]', s):
                    continue
                out.add(s)
items = sorted(out)
body = ',\n'.join('  ' + json.dumps(s, ensure_ascii=False).replace('$', r'\$') for s in items)
(root / 'lib/i18n/app_strings.g.dart').write_text(
    '// Generated by tool/extract_strings.py. Do not edit by hand.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n'
    f'const appStrings = <String>[\n{body},\n];\n')
print(len(items), 'strings')
